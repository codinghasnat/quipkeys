#!/usr/bin/env python3
"""Add common words that the Google Books list lacks (American spellings,
interjections, modern words) using the `wordfreq` package's English data.

Usage: python3 -I scripts/build_wordfreq_supplement.py <large_en.msgpack.gz> data/en_unigrams.txt > data/en_wordfreq.txt
(needs the `msgpack` module on PYTHONPATH)

Web text contains plenty of frequent misspellings ("teh", "dont", "becuase"),
so a new word is only added if it is NOT a single edit away from a much more
frequent word. Contractions, which the Google list gives a placeholder count,
get their wordfreq count instead.
"""
import gzip, re, sys
import msgpack

MIN_ZIPF = 3.0  # one occurrence per million words
GOOGLE_TOTAL = 541808760578
BLOCK = {"alot", "im", "ive", "ur", "u", "thx", "pls", "plz", "dont", "didnt", "doesnt", "isnt",
         "wasnt", "thats", "whats", "youre", "theyre", "shouldnt", "wouldnt", "couldnt", "hes", "shes"}

wf_path, google_path = sys.argv[1], sys.argv[2]
bins = msgpack.unpackb(gzip.open(wf_path).read(), raw=False)[1:]
freq = {}
for cb, words in enumerate(bins):
    for w in words:
        freq.setdefault(w, 10 ** (-cb / 100))

google = {}
for line in open(google_path):
    w, c = line.split()
    google[w] = int(c)

def edits1(w):
    letters = "abcdefghijklmnopqrstuvwxyz'"
    splits = [(w[:i], w[i:]) for i in range(len(w) + 1)]
    for a, b in splits:
        if b:
            yield a + b[1:]
        if len(b) > 1:
            yield a + b[1] + b[0] + b[2:]
        for c in letters:
            if b:
                yield a + c + b[1:]
            yield a + c + b

out = []
for w, f in freq.items():
    if not re.fullmatch(r"[a-z][a-z']*", w) or len(w) < 2 or w in BLOCK:
        continue
    count = int(f * GOOGLE_TOTAL)
    if w in google:
        if google[w] == 300000 and "'" in w:
            out.append((w, count))
        continue
    if 9 + __import__("math").log10(f) < (MIN_ZIPF if len(w) > 2 else 4.0):
        continue
    if w.endswith("'") or w.startswith("'"):
        continue
    # Probably a common misspelling of a much more frequent word?
    # Dropped apostrophes ("dont") need only a 10x gap; short words a big one.
    ratio = 300 if len(w) <= 3 else 100
    if any(freq.get(e, 0) > (10 if "'" in e else ratio) * f for e in set(edits1(w)) if e != w):
        continue
    out.append((w, count))

# Spelling variants: if one of a US/UK pair is known, make sure the other is.
VARIANTS = [("our", "or"), ("ise", "ize"), ("ised", "ized"), ("ises", "izes"), ("ising", "izing"),
            ("isation", "ization"), ("isations", "izations"), ("yse", "yze"), ("ysed", "yzed"),
            ("ysing", "yzing"), ("lled", "led"), ("lling", "ling"), ("ller", "ler"), ("llers", "lers"),
            ("tre", "ter"), ("tres", "ters"), ("ogue", "og"), ("ence", "ense"), ("lment", "lment")]
added = {w for w, _ in out}
def variants(w):
    for a, b in VARIANTS:
        for x, y in ((a, b), (b, a)):
            if w.endswith(x) and len(w) > len(x) + 2:
                yield w[: -len(x)] + y
    for x, y in (("our", "or"), ("or", "our")):
        i = w.find(x)
        if 2 < i < len(w) - len(x):
            yield w[:i] + y + w[i + len(x):]
    for i in range(1, len(w) - 1):  # enrollment/enrolment, skillful/skilful
        if w[i] == w[i - 1] == "l":
            yield w[:i] + w[i + 1:]
        elif w[i] == "l" and w[i - 1] != "l":
            yield w[:i] + "l" + w[i:]

def variants2(w):
    for v in variants(w):
        yield v
        yield from variants(v)
for w, f in freq.items():
    if w in google or w in added or not re.fullmatch(r"[a-z]+", w) or len(w) < 5:
        continue
    if 9 + __import__("math").log10(f) < 1.0:
        continue
    for v in variants2(w):
        if v in google:
            out.append((w, max(int(f * GOOGLE_TOTAL), google[v] // 4)))
            added.add(w)
            break

out.sort(key=lambda x: -x[1])
print("# Generated by scripts/build_wordfreq_supplement.py from wordfreq 3.1.1 (large_en).")
for w, c in out:
    print(w, c)
print(f"{len(out)} entries", file=sys.stderr)
